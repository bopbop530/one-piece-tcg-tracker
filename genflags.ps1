"@

($header + "`n" + ($lines -join "`n") + "`n];`n") | Out-File -Encoding utf8 (Join-Path $here 'imgflags.js')
Write-Host "no-artwork: $nPlaceholder   wrong-artwork: $nShared   rows: $($rows.Count)"
