$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$report = Get-Content (Join-Path $here 'dupart.json') -Raw -Encoding UTF8 | ConvertFrom-Json

# A name counts as the PLAIN printing when nothing is left after removing the
# bare card number the source likes to repeat: "Nami (OP15-108)" is plain,
# "Nami (OP15-108) (Dash Pack)" is not.
function Is-Plain($name) {
  $n = $name
  $n = [regex]::Replace($n, '\s*\(\s*(?:[A-Z]{1,4}\d{2}-\d{3}|\d{3})\s*\)', '')
  $n = [regex]::Replace($n, '\s*-\s*[A-Z]{1,4}\d{2}-\d{3}', '')
  $n = [regex]::Replace($n, '\s*-\s*P-\d{3}', '')
  return -not ($n -match '[\(\[]')
}

$rows = New-Object System.Collections.ArrayList
$nPlaceholder = 0; $nShared = 0

foreach ($g in $report) {
  $members = @($g.members)
  # A genuine mix-up is a pair. One file handed to dozens of cards is the
  # source's "no picture yet" placeholder, which is a different problem.
  $isPlaceholder = $members.Count -gt 5
  if ($isPlaceholder) {
    foreach ($m in $members) {
      [void]$rows.Add([pscustomobject]@{ f = ($m.url -split '/')[-1]; k = 0; o = ''; n = $m.name })
      $nPlaceholder++
    }
    continue
  }
  $plain = @($members | Where-Object { Is-Plain $_.name })
  foreach ($m in $members) {
    # The plain printing legitimately owns the artwork. Only flag it when every
    # member is a variant and there is no way to tell which is the impostor.
    if ($plain.Count -eq 1 -and $plain[0].name -eq $m.name) { continue }
    $others = (@($members | Where-Object { $_.name -ne $m.name } | ForEach-Object { $_.name }) | Sort-Object -Unique) -join ', '
    [void]$rows.Add([pscustomobject]@{ f = ($m.url -split '/')[-1]; k = 1; o = $others; n = $m.name })
    $nShared++
  }
}

$rows = $rows | Sort-Object k, n
$lines = $rows | ForEach-Object {
  "  [$(ConvertTo-Json $_.f -Compress), $($_.k), $(ConvertTo-Json $_.o -Compress)],  // $($_.n)"
}

